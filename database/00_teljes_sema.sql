-- A PostgreSQL-ben nincs `ALTER TABLE ... ADD CONSTRAINT IF NOT EXISTS`,
-- ezért egy segédfüggvény ellenőrzi, hogy létezik-e már a megszorítás.
CREATE OR REPLACE FUNCTION app_add_constraint(
    p_table      TEXT,
    p_constraint TEXT,
    p_definition TEXT
) RETURNS VOID
LANGUAGE plpgsql AS $fn$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM   pg_constraint c
        JOIN   pg_class      t ON t.oid = c.conrelid
        JOIN   pg_namespace  n ON n.oid = t.relnamespace
        WHERE  n.nspname = 'public'
          AND  t.relname = p_table
          AND  c.conname = p_constraint
    ) THEN
        EXECUTE format('ALTER TABLE public.%I ADD CONSTRAINT %I %s',
                       p_table, p_constraint, p_definition);
    END IF;
END;
$fn$;

-- Megszorítás biztonságos eltávolítása (séma-evolúcióhoz).
CREATE OR REPLACE FUNCTION app_drop_constraint(
    p_table      TEXT,
    p_constraint TEXT
) RETURNS VOID
LANGUAGE plpgsql AS $fn$
BEGIN
    EXECUTE format('ALTER TABLE public.%I DROP CONSTRAINT IF EXISTS %I',
                   p_table, p_constraint);
END;
$fn$;

-- updated_at karbantartás.
CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger
LANGUAGE plpgsql AS $fn$
BEGIN
    NEW.updated_at := now();
    RETURN NEW;
END;
$fn$;



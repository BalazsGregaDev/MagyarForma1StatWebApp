-- 4.1 Versenyző életkora legalább 18 év
CREATE OR REPLACE FUNCTION trg_check_driver_age() RETURNS trigger
LANGUAGE plpgsql AS $fn$
BEGIN
    IF NEW."BirthDate" IS NOT NULL
       AND age(CURRENT_DATE, NEW."BirthDate") < INTERVAL '18 years' THEN
        RAISE EXCEPTION 'A pilótának legalább 18 évesnek kell lennie (%)', NEW."Name"
            USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
END;
$fn$;

-- 4.2 Csapat alapítási éve nem lehet a jövőben
CREATE OR REPLACE FUNCTION trg_check_founded_year() RETURNS trigger
LANGUAGE plpgsql AS $fn$
BEGIN
    IF NEW."FoundedYear" > EXTRACT(YEAR FROM CURRENT_DATE) THEN
        RAISE EXCEPTION 'Az alapítás éve nem lehet a jövőben (%)', NEW."FoundedYear"
            USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
END;
$fn$;

-- 4.3 Mezőnyméret: 2024-től max. 20, korábban max. 26 pozíció
CREATE OR REPLACE FUNCTION trg_race_result_validate() RETURNS trigger
LANGUAGE plpgsql AS $fn$
DECLARE
    v_year  SMALLINT;
    v_count INTEGER;
    v_max   INTEGER;
BEGIN
    IF NEW."Position" IS NULL THEN
        RETURN NEW;
    END IF;

    SELECT "Year" INTO v_year FROM grandprix
    WHERE "GrandPrixID" = NEW."GrandPrixID";

    v_max := CASE WHEN v_year >= 2024 THEN 20 ELSE 26 END;

    SELECT COUNT(*) INTO v_count
    FROM   race_result
    WHERE  "GrandPrixID" = NEW."GrandPrixID"
      AND  "GpOrSprint"  = NEW."GpOrSprint"
      AND  "Position" IS NOT NULL
      AND  "ResultID" IS DISTINCT FROM NEW."ResultID";

    IF v_count >= v_max THEN
        RAISE EXCEPTION '% évi futamon legfeljebb % pozíció rögzíthető', v_year, v_max
            USING ERRCODE = 'check_violation';
    END IF;

    RETURN NEW;
END;
$fn$;

-- 4.4 Automatikus pontkiosztás
--
--  A MySQL sémában KÉT versengő BEFORE INSERT trigger írta a Points mezőt,
--  a második felülírta az elsőt. Itt egyetlen, teljes lefedettségű függvény,
--  és INSERT-re és UPDATE-re egyaránt fut.
CREATE OR REPLACE FUNCTION trg_assign_points() RETURNS trigger
LANGUAGE plpgsql AS $fn$
DECLARE
    v_year   SMALLINT;
    v_points NUMERIC(4,1) := 0;
BEGIN
    IF NEW."Position" IS NULL THEN
        NEW."Points" := 0;
        RETURN NEW;
    END IF;

    SELECT "Year" INTO v_year FROM grandprix
    WHERE "GrandPrixID" = NEW."GrandPrixID";

    IF NEW."GpOrSprint" = FALSE THEN
        -- Sprint (2021-től): 8-7-6-5-4-3-2-1
        v_points := CASE NEW."Position"
            WHEN 1 THEN 8 WHEN 2 THEN 7 WHEN 3 THEN 6 WHEN 4 THEN 5
            WHEN 5 THEN 4 WHEN 6 THEN 3 WHEN 7 THEN 2 WHEN 8 THEN 1
            ELSE 0 END;

    ELSIF v_year >= 2010 THEN
        v_points := CASE NEW."Position"
            WHEN 1 THEN 25 WHEN 2  THEN 18 WHEN 3 THEN 15 WHEN 4 THEN 12
            WHEN 5 THEN 10 WHEN 6  THEN  8 WHEN 7 THEN  6 WHEN 8 THEN  4
            WHEN 9 THEN  2 WHEN 10 THEN  1
            ELSE 0 END;

    ELSIF v_year BETWEEN 2003 AND 2009 THEN
        v_points := CASE NEW."Position"
            WHEN 1 THEN 10 WHEN 2 THEN 8 WHEN 3 THEN 6 WHEN 4 THEN 5
            WHEN 5 THEN  4 WHEN 6 THEN 3 WHEN 7 THEN 2 WHEN 8 THEN 1
            ELSE 0 END;

    ELSIF v_year BETWEEN 1991 AND 2002 THEN
        v_points := CASE NEW."Position"
            WHEN 1 THEN 10 WHEN 2 THEN 6 WHEN 3 THEN 4
            WHEN 4 THEN  3 WHEN 5 THEN 2 WHEN 6 THEN 1
            ELSE 0 END;
    END IF;

    -- Leggyorsabb körért járó +1 pont (2019-2024, futamon, top10).
    -- Az eredeti sémában ez elveszett: a seeder 26-ot írt, a trigger 25-re
    -- csökkentette. A chk_points_range felső határa (26) pont ezt engedi meg.
    IF NEW."FastestLap"
       AND NEW."GpOrSprint"
       AND v_year BETWEEN 2019 AND 2024
       AND NEW."Position" <= 10 THEN
        v_points := v_points + 1;
    END IF;

    NEW."Points" := v_points;
    RETURN NEW;
END;
$fn$;

-- 4.5 Futamgyőztes szinkronizálása
CREATE OR REPLACE FUNCTION trg_sync_race_winner() RETURNS trigger
LANGUAGE plpgsql AS $fn$
DECLARE
    v_gp     BIGINT := COALESCE(NEW."GrandPrixID", OLD."GrandPrixID");
    v_winner BIGINT;
BEGIN
    SELECT "DriverID" INTO v_winner
    FROM   race_result
    WHERE  "GrandPrixID" = v_gp
      AND  "GpOrSprint"  = TRUE
      AND  "Position"    = 1
    LIMIT  1;

    UPDATE grandprix
    SET    "WinnerDriverID" = v_winner
    WHERE  "GrandPrixID" = v_gp
      AND  "WinnerDriverID" IS DISTINCT FROM v_winner;

    RETURN NULL;
END;
$fn$;

-- 4.6 Futamgyőztes kézi módosításának tiltása
--
--  Két kivétel:
--   - pg_trigger_depth() > 1  -> a 4.5-ös trigger írja, ez legitim
--   - app.allow_winner_override = 'on' -> szándékos admin felülbírálás:
--       SET LOCAL app.allow_winner_override = 'on';
CREATE OR REPLACE FUNCTION trg_lock_race_winner() RETURNS trigger
LANGUAGE plpgsql AS $fn$
BEGIN
    IF pg_trigger_depth() > 1 THEN
        RETURN NEW;
    END IF;

    IF COALESCE(current_setting('app.allow_winner_override', TRUE), 'off') = 'on' THEN
        RETURN NEW;
    END IF;

    IF OLD."WinnerDriverID" IS NOT NULL
       AND NEW."WinnerDriverID" IS NOT NULL
       AND NEW."WinnerDriverID" <> OLD."WinnerDriverID" THEN
        RAISE EXCEPTION 'Egy verseny győztese nem módosítható közvetlenül. Írd át a futameredményt, vagy: SET LOCAL app.allow_winner_override = ''on'';'
            USING ERRCODE = 'check_violation';
    END IF;

    RETURN NEW;
END;
$fn$;



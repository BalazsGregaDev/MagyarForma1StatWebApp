DROP VIEW IF EXISTS v_driver_standings      CASCADE;
DROP VIEW IF EXISTS v_constructor_standings CASCADE;
DROP VIEW IF EXISTS v_driver_race_points    CASCADE;

CREATE VIEW v_driver_standings AS
SELECT  d."DriverID",
        d."Name"       AS driver_name,
        d."Nationality",
        d."DriverNumber",
        d."Acronym",
        d."Image",
        d."ConstructorID",
        c."Name"       AS constructor_name,
        c."TeamColour" AS team_colour,
        COALESCE(SUM(r."Points"), 0)::NUMERIC                           AS points,
        COUNT(*) FILTER (WHERE r."Position" = 1  AND r."GpOrSprint")     AS wins,
        COUNT(*) FILTER (WHERE r."Position" <= 3 AND r."GpOrSprint")     AS podiums,
        COUNT(*) FILTER (WHERE r."FastestLap")                           AS fastest_laps,
        COUNT(*) FILTER (WHERE r."GpOrSprint")                           AS races,
        COUNT(*) FILTER (WHERE r."Position" IS NULL AND r."GpOrSprint")  AS dnfs
FROM        drivers      d
LEFT JOIN   race_result  r ON r."DriverID"      = d."DriverID"
LEFT JOIN   constructors c ON c."ConstructorID" = d."ConstructorID"
GROUP BY    d."DriverID", d."Name", d."Nationality", d."DriverNumber",
            d."Acronym", d."Image", d."ConstructorID", c."Name", c."TeamColour";

CREATE VIEW v_constructor_standings AS
SELECT  c."ConstructorID",
        c."Name"       AS constructor_name,
        c."Nationality",
        c."Image",
        c."TeamColour" AS team_colour,
        COALESCE(SUM(r."Points"), 0)::NUMERIC                            AS points,
        COUNT(*) FILTER (WHERE r."Position" = 1  AND r."GpOrSprint")      AS wins,
        COUNT(*) FILTER (WHERE r."Position" <= 3 AND r."GpOrSprint")      AS podiums,
        COUNT(*) FILTER (WHERE r."FastestLap")                            AS fastest_laps,
        COUNT(DISTINCT r."GrandPrixID") FILTER (WHERE r."GpOrSprint")     AS races
FROM        constructors c
LEFT JOIN   race_result  r ON r."ConstructorID" = c."ConstructorID"
GROUP BY    c."ConstructorID", c."Name", c."Nationality", c."Image", c."TeamColour";

-- Futamonkénti pontbontás a statisztika-oldal oszlopdiagramjához.
CREATE VIEW v_driver_race_points AS
SELECT  r."DriverID",
        g."GrandPrixID",
        g."Name"    AS grand_prix_name,
        g."Country",
        g."Year",
        g."Round",
        SUM(r."Points")::NUMERIC AS points
FROM        race_result r
JOIN        grandprix   g ON g."GrandPrixID" = r."GrandPrixID"
GROUP BY    r."DriverID", g."GrandPrixID", g."Name", g."Country", g."Year", g."Round";

COMMENT ON VIEW v_driver_standings IS
    'A FILTER (WHERE "GpOrSprint") záradék az, ami a Laravel backendből hiányzott: enélkül a sprintgyőzelmek is futamgyőzelemnek számítottak.';



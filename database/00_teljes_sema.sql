--  9. NÉZETEK – a StatisticsController aggregációi adatbázis-oldalon
--
--  DROP + CREATE: a nézet nem tárol adatot, így veszteségmentes, és akkor
--  is működik, ha az oszloplista változott (a CREATE OR REPLACE hibázna).

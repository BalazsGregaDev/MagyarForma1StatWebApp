CREATE OR REPLACE FUNCTION driver_stats(p_driver_id BIGINT)
RETURNS JSON
LANGUAGE sql STABLE AS $fn$
    SELECT json_build_object(
        'driver',       (SELECT row_to_json(s) FROM v_driver_standings s
                         WHERE s."DriverID" = p_driver_id),
        'points_chart', COALESCE((SELECT json_agg(p ORDER BY p."Year", p."Round", p."GrandPrixID")
                                  FROM v_driver_race_points p
                                  WHERE p."DriverID" = p_driver_id), '[]'::json)
    );
$fn$;

CREATE OR REPLACE FUNCTION constructor_stats(p_constructor_id BIGINT)
RETURNS JSON
LANGUAGE sql STABLE AS $fn$
    SELECT json_build_object(
        'constructor',  (SELECT row_to_json(s) FROM v_constructor_standings s
                         WHERE s."ConstructorID" = p_constructor_id),
        'drivers',      COALESCE((SELECT json_agg(d ORDER BY d.points DESC)
                                  FROM v_driver_standings d
                                  WHERE d."ConstructorID" = p_constructor_id), '[]'::json),
        'points_chart', COALESCE((SELECT json_agg(x ORDER BY x."Year", x."Round", x."GrandPrixID")
                                  FROM (
                                      SELECT g."GrandPrixID", g."Name" AS grand_prix_name,
                                             g."Country", g."Year", g."Round",
                                             SUM(r."Points")::NUMERIC AS points
                                      FROM   race_result r
                                      JOIN   grandprix   g ON g."GrandPrixID" = r."GrandPrixID"
                                      WHERE  r."ConstructorID" = p_constructor_id
                                      GROUP  BY g."GrandPrixID", g."Name", g."Country", g."Year", g."Round"
                                  ) x), '[]'::json)
    );
$fn$;



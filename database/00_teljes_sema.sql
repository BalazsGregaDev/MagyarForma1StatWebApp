-- =====================================================================
--  15. IDENTITY SZEKVENCIÁK SZINKRONIZÁLÁSA
--
--  Ez a leggyakoribb Postgres-anomália migráció után: ha az adatokat
--  explicit ID-kkal töltöd be (INSERT ... ("DriverID", ...) VALUES (1, ...)),
--  a szekvencia nem lép, és a következő automatikus beszúrás
--  "duplicate key value violates unique constraint" hibával elszáll.
--
--  Ez a blokk minden futáskor újraigazítja a szekvenciákat.
-- =====================================================================

DO $do$
DECLARE
    r   RECORD;
    seq TEXT;
    mx  BIGINT;
BEGIN
    FOR r IN
        SELECT * FROM (VALUES
            ('circuits',          'CircuitID'),
            ('constructors',      'ConstructorID'),
            ('drivers',           'DriverID'),
            ('grandprix',         'GrandPrixID'),
            ('race_result',       'ResultID'),
            ('qualifying_result', 'QualifyingID'),
            ('teams_drivers',     'id'),
            ('laps',              'id'),
            ('pit_stops',         'id'),
            ('stints',            'id'),
            ('weather',           'id'),
            ('sync_log',          'id')
        ) AS t(tbl, col)
    LOOP
        seq := pg_get_serial_sequence('public.' || r.tbl, r.col);
        IF seq IS NOT NULL THEN
            EXECUTE format('SELECT COALESCE(MAX(%I), 0) FROM public.%I', r.col, r.tbl)
              INTO mx;
            PERFORM setval(seq, GREATEST(mx, 1), mx > 0);
        END IF;
    END LOOP;
END;
$do$;



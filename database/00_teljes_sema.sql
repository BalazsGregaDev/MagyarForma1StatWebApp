--  Ugyanaz a modell: mindenki olvas, csak az admin ír.
--  A szinkron a service_role kulccsal fut, ami megkerüli az RLS-t.
-- =====================================================================

ALTER TABLE laps      ENABLE ROW LEVEL SECURITY;
ALTER TABLE pit_stops ENABLE ROW LEVEL SECURITY;
ALTER TABLE stints    ENABLE ROW LEVEL SECURITY;
ALTER TABLE weather   ENABLE ROW LEVEL SECURITY;
ALTER TABLE sync_log  ENABLE ROW LEVEL SECURITY;

DO $do$
DECLARE t TEXT;
BEGIN
    FOREACH t IN ARRAY ARRAY['laps','pit_stops','stints','weather']
    LOOP
        EXECUTE format('DROP POLICY IF EXISTS public_read ON public.%I', t);
        EXECUTE format('DROP POLICY IF EXISTS admin_write ON public.%I', t);
        EXECUTE format('CREATE POLICY public_read ON public.%I
                        FOR SELECT TO anon, authenticated USING (TRUE)', t);
        EXECUTE format('CREATE POLICY admin_write ON public.%I
                        FOR ALL TO authenticated
                        USING (public.is_admin()) WITH CHECK (public.is_admin())', t);
    END LOOP;
END;
$do$;

-- A szinkron-naplót csak admin láthatja: üzemeltetési adat.
